"""Merge the JSON chunks into research-data.json.

Each chunk is a raw JSON document; this script assembles them into the
final research database consumed by the static site.
"""

import json
import os

BASE = os.path.join(os.path.dirname(os.path.abspath(__file__)), "chunks")
OUT = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "research-data.json")

FILES = {
    "meta": "00-meta.json",
    "models": "01-models.json",
    "datasets": "02-datasets.json",
    "xai_methods": "03-xai.json",
    "papers": "04-papers.json",
    "repositories": "05-repos.json",
    "recommendations": "06-recommendations.json",
}


def load(name):
    # utf-8-sig tolerates a BOM, which Windows text editors add silently.
    with open(os.path.join(BASE, name), encoding="utf-8-sig") as f:
        return json.load(f)


def main():
    data = {"meta": load(FILES["meta"])}
    for key in ("models", "datasets", "xai_methods", "papers", "repositories"):
        data[key] = load(FILES[key])

    rec = load(FILES["recommendations"])
    data["recommendations"] = rec["options"]
    data["recommended"] = rec["recommended"]
    data["top_models"] = rec["top5"]
    data["project_architecture"] = rec["architecture"]
    data["verification"] = rec["verification"]

    # Keep the declared counts honest.
    counts = data["meta"]["counts"]
    counts["models"] = len(data["models"])
    counts["datasets"] = len(data["datasets"])
    counts["xai_methods"] = len(data["xai_methods"])
    counts["papers"] = len(data["papers"])
    counts["repositories"] = len(data["repositories"])
    counts["recommendations"] = len(data["recommendations"])
    data["meta"]["counts"] = counts

    with open(OUT, "w", encoding="utf-8") as f:
        json.dump(data, f, indent=2, ensure_ascii=False)

    # Also emit a JS wrapper so the site works when opened directly from the
    # filesystem (fetch() of a local .json is blocked by the browser's CORS
    # rules on file:// origins).
    js_out = os.path.join(os.path.dirname(OUT), "research-data.js")
    with open(js_out, "w", encoding="utf-8") as f:
        f.write("/* Auto-generated by tools/build_data.py - do not edit by hand. */\n")
        f.write("window.RESEARCH_DATA = ")
        json.dump(data, f, indent=2, ensure_ascii=False)
        f.write(";\n")

    print(f"wrote {OUT}")
    print(f"wrote {js_out}")
    for k in ("models", "datasets", "xai_methods", "papers", "repositories", "recommendations"):
        print(f"  {k}: {len(data[k])}")


if __name__ == "__main__":
    main()
